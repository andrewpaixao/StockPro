import psycopg
from psycopg.rows import dict_row

from flask import (
    Flask, render_template, request, redirect,
    url_for, flash, session
)
from werkzeug.security import generate_password_hash, check_password_hash


app = Flask(__name__)
app.secret_key = os.environ.get(
    "STOCKPRO_SECRET_KEY",
    "troque-esta-chave-por-uma-chave-privada"
)

BANCO = Path(__file__).resolve().parent / "stockpro.db"


def usar_postgres():
    return bool(os.environ.get("STOCKPRO_DATABASE_URL"))


def conectar():
    if usar_postgres():
        return psycopg.connect(
            os.environ["STOCKPRO_DATABASE_URL"],
            row_factory=dict_row
        )

    conexao = sqlite3.connect(str(BANCO))
    conexao.row_factory = sqlite3.Row
    conexao.execute("PRAGMA foreign_keys = ON")
    return conexao


def executar(banco, sql, parametros=()):
    if usar_postgres():
        sql = sql.replace(
            "nome COLLATE NOCASE = ?",
            "LOWER(nome) = LOWER(?)"
        )
        sql = sql.replace("?", "%s")

    return banco.execute(sql, parametros)


def iniciar_banco():
    with conectar() as banco:
        if usar_postgres():
            banco.execute("""
                CREATE TABLE IF NOT EXISTS loja (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    nome TEXT NOT NULL,
                    cnpj TEXT NOT NULL UNIQUE,
                    proprietario TEXT NOT NULL,
                    contato TEXT NOT NULL,
                    senha_hash TEXT
                )
            """)

            banco.execute("""
                CREATE TABLE IF NOT EXISTS estoque (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    loja_id BIGINT NOT NULL UNIQUE,
                    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    FOREIGN KEY (loja_id) REFERENCES loja(id)
                )
            """)

            banco.execute("""
                CREATE TABLE IF NOT EXISTS produtos (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    estoque_id BIGINT NOT NULL,
                    nome TEXT NOT NULL,
                    preco DOUBLE PRECISION NOT NULL CHECK (preco > 0),
                    quantidade INTEGER NOT NULL CHECK (quantidade >= 0),
                    FOREIGN KEY (estoque_id) REFERENCES estoque(id),
                    UNIQUE (estoque_id, nome)
                )
            """)

        else:
            banco.executescript("""
                CREATE TABLE IF NOT EXISTS loja (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    nome TEXT NOT NULL,
                    cnpj TEXT NOT NULL UNIQUE,
                    proprietario TEXT NOT NULL,
                    contato TEXT NOT NULL,
                    senha_hash TEXT
                );

                CREATE TABLE IF NOT EXISTS estoque (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    loja_id INTEGER NOT NULL UNIQUE,
                    criado_em TEXT DEFAULT CURRENT_TIMESTAMP,
                    FOREIGN KEY (loja_id) REFERENCES loja(id)
                );

                CREATE TABLE IF NOT EXISTS produtos (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    estoque_id INTEGER NOT NULL,
                    nome TEXT NOT NULL,
                    preco REAL NOT NULL CHECK (preco > 0),
                    quantidade INTEGER NOT NULL CHECK (quantidade >= 0),
                    FOREIGN KEY (estoque_id) REFERENCES estoque(id),
                    UNIQUE (estoque_id, nome)
                );
            """)

            colunas = {
                linha["name"]
                for linha in banco.execute(
                    "PRAGMA table_info(loja)"
                ).fetchall()
            }

            if "senha_hash" not in colunas:
                banco.execute(
                    "ALTER TABLE loja ADD COLUMN senha_hash TEXT"
                )


def obter_loja():
    loja_id = session.get("loja_id")

    if not loja_id:
        return None

    with conectar() as banco:
        return executar(
            banco,
            "SELECT * FROM loja WHERE id = ?",
            (loja_id,)
        ).fetchone()


def obter_estoque():
    loja = obter_loja()

    if loja is None:
        return None

    with conectar() as banco:
        return executar(
            banco,
            "SELECT * FROM estoque WHERE loja_id = ?",
            (loja["id"],)
        ).fetchone()


def exigir_login(funcao):
    @wraps(funcao)
    def wrapper(*args, **kwargs):
        if obter_loja() is None:
            flash("Entre na sua conta para continuar.")
            return redirect(url_for("login"))

        return funcao(*args, **kwargs)

    return wrapper


@app.route("/")
def pagina_inicial():
    loja = obter_loja()
    estoque = obter_estoque()

    return render_template(
        "home.html",
        loja=loja,
        estoque=estoque
    )


@app.route("/cadastrar-loja", methods=["GET", "POST"])
def cadastrar_loja():
    if obter_loja() is not None:
        return redirect(url_for("pagina_inicial"))

    if request.method == "POST":
        nome = request.form.get("nome", "").strip()
        cnpj = request.form.get("cnpj", "").strip()
        proprietario = request.form.get("proprietario", "").strip()
        contato = request.form.get("contato", "").strip()
        senha = request.form.get("senha", "")
        confirmar_senha = request.form.get("confirmar_senha", "")

        if not all([
            nome, cnpj, proprietario, contato,
            senha, confirmar_senha
        ]):
            flash("Preencha todos os campos.")
            return render_template("loja.html")

        if len(senha) < 8:
            flash("A senha deve ter pelo menos 8 caracteres.")
            return render_template("loja.html")

        if senha != confirmar_senha:
            flash("As senhas não coincidem.")
            return render_template("loja.html")

        try:
            with conectar() as banco:
                sql = """
                    INSERT INTO loja
                    (nome, cnpj, proprietario, contato, senha_hash)
                    VALUES (?, ?, ?, ?, ?)
                """

                cursor = executar(
                    banco,
                    sql + (" RETURNING id" if usar_postgres() else ""),
                    (
                        nome,
                        cnpj,
                        proprietario,
                        contato,
                        generate_password_hash(senha)
                    )
                )

                if usar_postgres():
                    nova_loja_id = cursor.fetchone()["id"]
                else:
                    nova_loja_id = cursor.lastrowid

            session.clear()
            session["loja_id"] = nova_loja_id

            flash("Loja cadastrada com sucesso!")
            return redirect(url_for("pagina_inicial"))

        except (sqlite3.IntegrityError, psycopg.IntegrityError):
            flash("Esse CNPJ já está cadastrado.")

    return render_template("loja.html")


@app.route("/login", methods=["GET", "POST"])
def login():
    if obter_loja() is not None:
        return redirect(url_for("pagina_inicial"))

    if request.method == "POST":
        cnpj = request.form.get("cnpj", "").strip()
        senha = request.form.get("senha", "")

        with conectar() as banco:
            loja = executar(
                banco,
                "SELECT * FROM loja WHERE cnpj = ?",
                (cnpj,)
            ).fetchone()

        if loja is None:
            flash("CNPJ ou senha incorretos.")

        elif not loja["senha_hash"]:
            flash("Sua loja antiga precisa ser ativada.")
            return redirect(url_for("ativar_conta"))

        elif not check_password_hash(loja["senha_hash"], senha):
            flash("CNPJ ou senha incorretos.")

        else:
            session.clear()
            session["loja_id"] = loja["id"]

            flash("Login realizado com sucesso!")
            return redirect(url_for("pagina_inicial"))

    return render_template("login.html")


@app.route("/ativar-conta", methods=["GET", "POST"])
def ativar_conta():
    if obter_loja() is not None:
        return redirect(url_for("pagina_inicial"))

    if request.method == "POST":
        cnpj = request.form.get("cnpj", "").strip()
        contato = request.form.get("contato", "").strip()
        senha = request.form.get("senha", "")
        confirmar_senha = request.form.get("confirmar_senha", "")

        if not all([cnpj, contato, senha, confirmar_senha]):
            flash("Preencha todos os campos.")

        elif len(senha) < 8:
            flash("A senha deve ter pelo menos 8 caracteres.")

        elif senha != confirmar_senha:
            flash("As senhas não coincidem.")

        else:
            with conectar() as banco:
                loja = executar(
                    banco,
                    """
                    SELECT * FROM loja
                    WHERE cnpj = ? AND contato = ?
                    """,
                    (cnpj, contato)
                ).fetchone()

                if loja is None:
                    flash("CNPJ ou contato não encontrados.")

                elif loja["senha_hash"]:
                    flash("Essa loja já possui uma senha.")
                    return redirect(url_for("login"))

                else:
                    executar(
                        banco,
                        """
                        UPDATE loja
                        SET senha_hash = ?
                        WHERE id = ?
                        """,
                        (
                            generate_password_hash(senha),
                            loja["id"]
                        )
                    )

                    session.clear()
                    session["loja_id"] = loja["id"]

                    flash("Conta ativada! Dados preservados.")
                    return redirect(url_for("pagina_inicial"))

    return render_template("ativar_conta.html")


